ANNOTATION_COLORS = {
    "high":   (0, 200, 83),      # Green  — confidence >= 0.75
    "medium": (0, 191, 255),     # Cyan   — confidence >= 0.50
    "low":    (0, 100, 255),     # Orange — confidence < 0.50
}

def get_confidence_color(confidence: float) -> tuple:
    """Return BGR color based on confidence level."""
    if confidence >= 0.75:
        return ANNOTATION_COLORS["high"]
    elif confidence >= 0.50:
        return ANNOTATION_COLORS["medium"]
    else:
        return ANNOTATION_COLORS["low"]

